  frag "wa-worker=3 ps-worker=1"
  out="$(pilot_clamp 2 1)"; has "$out" "WA=3 PS=1" "RED on the .4 tree: the engine raised wa-worker to 3 (agent.toml 2), the plist says 2 -> the Pilot admits 3 without a plist edit"; has "$out" "PILOT_WA_WORKER_MAX 2 sobe ao teto do motor 3" "and the sweep log says it followed the engine UP"
  out="$(pilot_clamp 4 1)"; has "$out" "WA=3 PS=1" "plist 4 (the code's own default) over the effective 3 -> 3"; has "$out" "limitado ao teto do motor 3" "said as a limit, as before"
