#!/usr/bin/env bash
# pool-ceiling-effective-cap.selftest.sh (ga-m9x0lb.4)
#
# Proves that the dispatchers' view of "the cap the CONTROLLER will run" is the EFFECTIVE one: the smaller of agents/<pool>/agent.toml and the
# engine's generated fragment (.gc/pool-ceiling-engine.toml, the dynamic engine ceiling, ga-m9x0lb). Measured 26/10 00:42: the engine had
# written gate-reviewer=2 (disk < 6 GB) and quality-gate-dispatcher.sh still logged "clamped to the engine cap 3" — it read agent.toml alone,
# so under pressure (exactly when the engine lowers the cap) the gate admitted one reviewer above the ceiling the controller enforces.
#   1. pool_ceiling_engine_cap_resolve / pool_ceiling_engine_cap (pool-ceiling.sh): fragment 2 + agent.toml 3 -> 2 (the RED case on the
#      pre-fix tree); fragment absent / empty / without an entry / ABOVE agent.toml -> agent.toml stands (never a raise); fragment foreign,
#      unreadable or its reader missing -> agent.toml stands AND the doubt is flagged and named; agent.toml unreadable -> the fragment's level.
#   2. pool_ceiling_step: the dynamic ceiling is bounded by the effective cap too.
#   3. the gate's REAL clamp block, extracted from quality-gate-dispatcher.sh, run under `set -euo pipefail` (the gate's mode).
#   4. the Pilot's REAL clamp block, extracted from pilot-dispatcher.sh (the static / shadow path the dynamic step does not cover).
# Hermetic: every scenario runs against a throwaway city under a temp dir; nothing under the real city is read or written.
# Run against the pre-patch tree to confirm RED. Override: POOL_CEILING_LIB / PILOT_DISPATCHER_PATH / GATE_DISPATCHER_PATH.

set -uo pipefail

SELF_DIR="$(cd "$(dirname "${BASH_SOURCE[0]}")" && pwd)"
LIB="${POOL_CEILING_LIB:-$SELF_DIR/pool-ceiling.sh}"
PILOT="${PILOT_DISPATCHER_PATH:-$SELF_DIR/pilot-dispatcher.sh}"
GATE="${GATE_DISPATCHER_PATH:-$SELF_DIR/quality-gate-dispatcher.sh}"

PASS=0; FAIL=0
ok()  { echo "  ✓ $*"; PASS=$((PASS+1)); }
bad() { echo "  ✗ $*"; FAIL=$((FAIL+1)); }
eq()  { if [ "$1" = "$2" ]; then ok "$3 (got: $1)"; else bad "$3 (expected: $2, got: $1)"; fi; }
has() { case "$1" in *"$2"*) ok "$3" ;; *) bad "$3 (missing '$2' in: $1)" ;; esac; }
lacks() { case "$1" in *"$2"*) bad "$3 (found '$2' in: $1)" ;; *) ok "$3" ;; esac; }
section() { echo; echo "── $* ──"; }

TMPROOT="$(mktemp -d)"
trap 'chmod -R u+rw "$TMPROOT" 2>/dev/null; rm -rf "$TMPROOT"' EXIT
# Never let a LIVE switch / fragment of the real city leak into this hermetic test.
export POOL_CEILING_ON_FILE="$TMPROOT/on.flag" POOL_CEILING_KILL_FILE="$TMPROOT/kill.off" POOL_CEILING_SHADOW_FILE="$TMPROOT/shadow.flag"
unset POOL_CEILING_ENGINE_FRAGMENT POOL_CEILING_ENGINE_SH POOL_CEILING_AGENTS_DIR POOL_CEILING_DYNAMIC GC_CITY

C=""
mk_city() { # <name> — wa-worker 4, ps-worker 2, gate-reviewer 3 in agent.toml; NO fragment yet
  C="$TMPROOT/$1"; mkdir -p "$C/.gc" "$C/agents/wa-worker" "$C/agents/ps-worker" "$C/agents/gate-reviewer"
  printf 'min_active_sessions = 0\nmax_active_sessions = 4\n' > "$C/agents/wa-worker/agent.toml"
  printf 'min_active_sessions = 0\nmax_active_sessions = 2\n' > "$C/agents/ps-worker/agent.toml"
  printf 'max_active_sessions = 3 # gate\nmin_active_sessions = 0\n' > "$C/agents/gate-reviewer/agent.toml"
}
frag() { # <"pool=level ..."> — a fragment in the shape the engine renders (header comments + [[patches.agent]] blocks)
  local e; { printf '# GENERATED by pool-ceiling-engine.sh\n# Empty or comment-only = no override.\n'; for e in $1; do printf '\n[[patches.agent]]\ndir = ""\nname = "%s"\nmax_active_sessions = %s\n' "${e%%=*}" "${e#*=}"; done; } > "$C/.gc/pool-ceiling-engine.toml"
}
FR() { echo "$C/.gc/pool-ceiling-engine.toml"; }

# resolve <pool> — runs the resolver in a fresh bash under the dispatchers' strict mode and prints "cap=<n> base=<n> doubt=<x>|<src>".
resolve() {
  bash -c 'set -euo pipefail; . "$1"; pool_ceiling_engine_cap_resolve "$2"; printf "cap=%s base=%s doubt=%s|%s" "$POOL_CEILING_ENGINE_CAP" "$POOL_CEILING_ENGINE_CAP_BASE" "$POOL_CEILING_ENGINE_CAP_DOUBT" "$POOL_CEILING_ENGINE_CAP_SRC"' _ "$LIB" "$1" 2>&1
}
cap_of() { printf '%s' "${1%%|*}" ; }

# ── 1. the resolver ───────────────────────────────────────────────────────────
section "1. pool_ceiling_engine_cap_resolve: the EFFECTIVE cap = the smaller of agent.toml and the fragment's entry"
export POOL_CEILING_AGENTS_DIR=""
mk_city c1; export POOL_CEILING_AGENTS_DIR="$C/agents"

# The case the bead is about. On the pre-fix tree pool_ceiling_engine_cap reads agent.toml alone and answers 3.
frag "gate-reviewer=2"
eq "$(bash -c 'set -euo pipefail; . "$1"; pool_ceiling_engine_cap gate-reviewer' _ "$LIB" 2>&1)" "2" "RED on the pre-fix tree: fragment gate-reviewer=2 + agent.toml 3 -> pool_ceiling_engine_cap says 2"
out="$(resolve gate-reviewer)"
eq "$(cap_of "$out")" "cap=2 base=3 doubt=" "resolve: cap 2, agent.toml alone is 3, no doubt"
has "$out" "fragmento pool-ceiling-engine.toml 2 (< agents/gate-reviewer/agent.toml 3)" "and the note says the number came from the fragment, and that it is below agent.toml"

frag "wa-worker=2 ps-worker=1 gate-reviewer=2"
eq "$(cap_of "$(resolve wa-worker)")" "cap=2 base=4 doubt=" "three entries: wa-worker is read from ITS entry (4 -> 2)"
eq "$(cap_of "$(resolve ps-worker)")" "cap=1 base=2 doubt=" "three entries: ps-worker is read from ITS entry (2 -> 1)"

# found / not-found: nothing overrides -> agent.toml stands, and the note says why
: > "$(FR)"
out="$(resolve gate-reviewer)"; eq "$(cap_of "$out")" "cap=3 base=3 doubt=" "fragment EMPTY (the kill switch's state) -> agent.toml 3, no doubt"; has "$out" "vazio" "the note says the fragment is empty"
printf '# only comments\n\n' > "$(FR)"
out="$(resolve gate-reviewer)"; eq "$(cap_of "$out")" "cap=3 base=3 doubt=" "fragment comment-only -> agent.toml 3"
rm -f "$(FR)"
out="$(resolve gate-reviewer)"; eq "$(cap_of "$out")" "cap=3 base=3 doubt=" "fragment ABSENT -> agent.toml 3, no doubt (no engine installed = nothing overrides)"; has "$out" "ausente" "the note says the fragment is absent"
frag "wa-worker=1"
out="$(resolve gate-reviewer)"; eq "$(cap_of "$out")" "cap=3 base=3 doubt=" "fragment with an entry for ANOTHER pool only -> agent.toml 3"; has "$out" "sem entrada para gate-reviewer" "the note says there is no entry for the pool"

# never a raise: a fragment ABOVE agent.toml (wa-worker, Athos rule) is not followed upward by a brake
frag "gate-reviewer=5"
out="$(resolve gate-reviewer)"; eq "$(cap_of "$out")" "cap=3 base=3 doubt=" "fragment 5 > agent.toml 3 -> 3 (a brake never raises)"; has "$out" "nao e menor" "the note says the fragment is not lower"

# could-not-find-out: the fragment EXISTS but cannot be consulted -> agent.toml stands, never a raise, and the doubt is flagged + named
printf 'garbage\n' > "$(FR)"
out="$(resolve gate-reviewer)"; eq "$(cap_of "$out")" "cap=3 base=3 doubt=1" "fragment FOREIGN -> agent.toml 3 AND doubt=1"; has "$out" "ESTRANHO" "the note says the fragment is foreign"; has "$out" "NAO consultado" "and that it was NOT consulted"
printf '[[patches.agent]]\ndir = ""\nname = "gate-reviewer"\nmax_active_sessions = 2\nmax_active_sessions = 1\n' > "$(FR)"
out="$(resolve gate-reviewer)"; eq "$(cap_of "$out")" "cap=3 base=3 doubt=1" "fragment with a DUPLICATED key (not what the engine writes) -> foreign -> agent.toml 3, doubt=1"
frag "gate-reviewer=2"
if [ "$(id -u)" = "0" ]; then echo "  - SKIPPED: unreadable-fragment case (running as root, chmod 000 does not stop a read)"
else
  chmod 000 "$(FR)"
  if [ -r "$(FR)" ]; then echo "  - SKIPPED: unreadable-fragment case (chmod 000 did not make the file unreadable here)"
  else
    out="$(resolve gate-reviewer)"; eq "$(cap_of "$out")" "cap=3 base=3 doubt=1" "fragment UNREADABLE -> agent.toml 3 AND doubt=1 (never read as 'no override' silently)"; has "$out" "ilegivel" "the note says it is unreadable"
  fi
  chmod 644 "$(FR)"
fi
out="$(POOL_CEILING_ENGINE_SH="$TMPROOT/does-not-exist.sh" resolve gate-reviewer)"
eq "$(cap_of "$out")" "cap=3 base=3 doubt=1" "the engine's reader MISSING while a fragment exists -> agent.toml 3, doubt=1"; has "$out" "indisponivel" "the note says the reader is unavailable"
out="$(POOL_CEILING_ENGINE_SH="$SELF_DIR/pool-ceiling.sh" resolve gate-reviewer)"
eq "$(cap_of "$out")" "cap=3 base=3 doubt=1" "a reader that does not define pce_fragment_parse -> agent.toml 3, doubt=1 (a broken reader is not 'no entry')"

# agent.toml unreadable
frag "gate-reviewer=2"; mv "$C/agents/gate-reviewer/agent.toml" "$C/agents/gate-reviewer/agent.toml.off"
out="$(resolve gate-reviewer)"; eq "$(cap_of "$out")" "cap=2 base= doubt=" "agent.toml MISSING + fragment 2 -> the fragment's 2 (a known lower bound beats a guess)"
rm -f "$(FR)"
out="$(resolve gate-reviewer)"; eq "$(cap_of "$out")" "cap= base= doubt=" "agent.toml MISSING + no fragment -> EMPTY (could not find out), never a number"; has "$out" "ILEGIVEL" "the note says the cap is unreadable"
eq "$(bash -c 'set -euo pipefail; . "$1"; pool_ceiling_engine_cap gate-reviewer; echo END' _ "$LIB" 2>&1)" "END" "pool_ceiling_engine_cap prints NOTHING when unreadable, and survives set -euo pipefail"
mv "$C/agents/gate-reviewer/agent.toml.off" "$C/agents/gate-reviewer/agent.toml"

# the READ itself fails: agent.toml is there and readable but `sed` exits non-zero (a stub that fails — the [ -r ] guard above is not what is under test)
SEDFAIL="$TMPROOT/sed-fails"; mkdir -p "$SEDFAIL"; printf '#!/bin/sh\nexit 2\n' > "$SEDFAIL/sed"; chmod +x "$SEDFAIL/sed"
frag "gate-reviewer=2"
out="$(PATH="$SEDFAIL:$PATH" resolve gate-reviewer)"; eq "$(cap_of "$out")" "cap=2 base= doubt=" "sed FAILS on a readable agent.toml + fragment 2 -> the fragment's 2, agent.toml read as unknown (survives set -euo pipefail)"
rm -f "$(FR)"
out="$(PATH="$SEDFAIL:$PATH" resolve gate-reviewer)"; eq "$(cap_of "$out")" "cap= base= doubt=" "sed FAILS + no fragment -> EMPTY, never a number"; has "$out" "ILEGIVEL" "and the note says the cap is unreadable"
eq "$(PATH="$SEDFAIL:$PATH" bash -c 'set -euo pipefail; . "$1"; pool_ceiling_engine_cap gate-reviewer; echo END' _ "$LIB" 2>&1)" "END" "pool_ceiling_engine_cap with a failing sed prints NOTHING and survives set -euo pipefail"

# the seams
mk_city c1b; export POOL_CEILING_AGENTS_DIR="$C/agents"
LIVELIKE="$TMPROOT/livelike"; mkdir -p "$LIVELIKE/.gc"; printf '[[patches.agent]]\ndir = ""\nname = "gate-reviewer"\nmax_active_sessions = 1\n' > "$LIVELIKE/.gc/pool-ceiling-engine.toml"
out="$(GC_CITY="$LIVELIKE" resolve gate-reviewer)"
eq "$(cap_of "$out")" "cap=3 base=3 doubt=" "hermetic: with POOL_CEILING_AGENTS_DIR set, a fragment under GC_CITY (the live one) is NOT read"
frag "gate-reviewer=2"
out="$(POOL_CEILING_ENGINE_FRAGMENT="$LIVELIKE/.gc/pool-ceiling-engine.toml" resolve gate-reviewer)"
eq "$(cap_of "$out")" "cap=1 base=3 doubt=" "POOL_CEILING_ENGINE_FRAGMENT wins over the path derived from the agents dir"
unset POOL_CEILING_AGENTS_DIR
out="$(GC_CITY="$C" resolve gate-reviewer)"
eq "$(cap_of "$out")" "cap=2 base=3 doubt=" "production shape (no seams, GC_CITY set): agents/ and .gc/ both come from GC_CITY"
out="$(resolve gate-reviewer)"
eq "$(cap_of "$out")" "cap= base= doubt=" "no GC_CITY and no seam -> unknown (empty), never a guess"

# ── 2. the step ───────────────────────────────────────────────────────────────
section "2. pool_ceiling_step: the dynamic ceiling never goes above the effective cap either"
mk_city c2; export POOL_CEILING_AGENTS_DIR="$C/agents"
step() { # <fixed> <min> <max> — prints RESULT; calm machine, queue 5, 3 live, dynamic ON
  bash -c '
    set -euo pipefail
    . "$1"
    export POOL_CEILING_DYNAMIC=1 POOL_CEILING_STATE_DIR="$2" POOL_CEILING_NOW=5000 POOL_CEILING_DRY=1
    export POOL_CEILING_T_LOAD5=31 POOL_CEILING_T_NCPU=10 POOL_CEILING_T_MEM=1 POOL_CEILING_T_SWAP_FREE_MB=5700 POOL_CEILING_T_SWAP_USED_MB=412 POOL_CEILING_T_DISK_FREE_MB=14336
    pool_ceiling_step gate-reviewer "$3" "$4" "$5" 3 5 ok ok
    printf "%s" "$POOL_CEILING_RESULT"
  ' _ "$LIB" "$TMPROOT/st.$RANDOM" "$1" "$2" "$3" 2>&1
}
frag "gate-reviewer=2"
eq "$(step 3 2 6)" "2" "RED on the pre-fix tree: fixed 3, bounds 2..6, fragment gate-reviewer=2 -> the ceiling is 2"
: > "$(FR)"
eq "$(step 3 2 6)" "3" "control: fragment empty -> 3 (agent.toml's cap), the step still works as before"
frag "gate-reviewer=2"; mv "$C/agents/gate-reviewer/agent.toml" "$C/agents/gate-reviewer/agent.toml.off"
eq "$(step 3 2 6)" "2" "agent.toml unreadable + fragment 2 -> 2 (and never above the fixed 3 on that doubt)"
mv "$C/agents/gate-reviewer/agent.toml.off" "$C/agents/gate-reviewer/agent.toml"

# ── 3. the gate ───────────────────────────────────────────────────────────────
section "3. quality-gate-dispatcher.sh: the REAL clamp block, run under set -euo pipefail"
unset POOL_CEILING_AGENTS_DIR
LOADER_X="$(sed -n '/SELFTEST-EXTRACT pool-ceiling-loader: BEGIN/,/SELFTEST-EXTRACT pool-ceiling-loader: END/p' "$GATE" 2>/dev/null)"
CLAMP_X="$(sed -n '/SELFTEST-EXTRACT gate-engine-cap-clamp: BEGIN/,/SELFTEST-EXTRACT gate-engine-cap-clamp: END/p' "$GATE" 2>/dev/null)"
if [ -z "$LOADER_X" ]; then bad "no SELFTEST-EXTRACT pool-ceiling-loader block in $GATE"
elif [ -z "$CLAMP_X" ]; then bad "RED on the pre-fix tree: no SELFTEST-EXTRACT gate-engine-cap-clamp block in $GATE (the clamp is inline and reads agent.toml alone)"
else
  gate_clamp() { # <GATE_MAX_REVIEWERS> — env from the caller (GC_CITY, POOL_CEILING_LIB). Prints "MAX=<n>" then "NOTE=<note>"
    GATE_MAX_REVIEWERS="$1" bash -c '
      set -euo pipefail
      eval "$1"; eval "$2"
      _gate_clamp_to_engine_cap
      echo "MAX=$GATE_MAX_REVIEWERS"; echo "NOTE=$GATE_ENGINE_CAP_NOTE"
    ' _ "$LOADER_X" "$CLAMP_X" 2>&1
  }
  mk_city g1; export GC_CITY="$C" POOL_CEILING_LIB="$LIB"
  frag "gate-reviewer=2"
  out="$(gate_clamp 6)"
  has "$out" "MAX=2" "RED on the pre-fix tree: fragment gate-reviewer=2 + agent.toml 3 + GATE_MAX_REVIEWERS 6 -> the gate's cap is 2"
  has "$out" "clamped to the engine cap 2" "the log note says the engine cap is 2"
  has "$out" "fragmento pool-ceiling-engine.toml 2" "and WHERE it came from: the fragment"
  out="$(gate_clamp 2)"; has "$out" "MAX=2" "GATE_MAX_REVIEWERS already 2 -> stays 2"; has "$out" "NOTE=" "no clamp needed"
  out="$(gate_clamp 1)"; has "$out" "MAX=1" "GATE_MAX_REVIEWERS 1 (below the cap) is never raised to it"
  out="$(gate_clamp 0)"; has "$out" "MAX=0" "GATE_MAX_REVIEWERS 0 (the operator's pause) stays 0"
  : > "$(FR)"
  out="$(gate_clamp 6)"; has "$out" "MAX=3" "fragment EMPTY -> the cap stays agent.toml's 3"; has "$out" "agents/gate-reviewer/agent.toml 3" "and the note says it came from agent.toml"; has "$out" "vazio" "and why the fragment did not count"
  rm -f "$(FR)"
  out="$(gate_clamp 6)"; has "$out" "MAX=3" "fragment ABSENT -> 3"; has "$out" "ausente" "and the note says absent"
  printf 'garbage\n' > "$(FR)"
  out="$(gate_clamp 6)"; has "$out" "MAX=3" "fragment FOREIGN -> 3 (no raise on a read failure)"; has "$out" "ESTRANHO" "and the note says foreign"
  out="$(gate_clamp 3)"; has "$out" "MAX=3" "foreign fragment, nothing to clamp (3 = 3)"; has "$out" "NOTE=engine cap 3" "but the doubt is still said out loud, with where the number came from"
  frag "gate-reviewer=2"; mv "$C/agents/gate-reviewer/agent.toml" "$C/agents/gate-reviewer/agent.toml.off"
  out="$(gate_clamp 6)"; has "$out" "MAX=2" "agent.toml unreadable + fragment 2 -> 2"
  rm -f "$(FR)"
  out="$(gate_clamp 6)"; has "$out" "MAX=6" "agent.toml unreadable + no fragment -> GATE_MAX_REVIEWERS stays (the old contract: never invent a cap)"; has "$out" "UNREADABLE" "and says so"
  mv "$C/agents/gate-reviewer/agent.toml.off" "$C/agents/gate-reviewer/agent.toml"
  # the lib did not load: agent.toml alone (the old reading), and the note says the fragment was NOT consulted
  frag "gate-reviewer=2"
  out="$(POOL_CEILING_LIB="$TMPROOT/no-such-lib.sh" gate_clamp 6)"
  has "$out" "MAX=3" "lib NOT loaded -> falls back to agent.toml's 3 (cannot read the fragment)"; has "$out" "NAO foi consultado" "and the note says the fragment was NOT consulted"
  # the fallback read fails: agent.toml missing, or sed itself exits non-zero -> UNREADABLE, GATE_MAX_REVIEWERS stays, the gate does not abort under set -e
  mv "$C/agents/gate-reviewer/agent.toml" "$C/agents/gate-reviewer/agent.toml.off"
  out="$(POOL_CEILING_LIB="$TMPROOT/no-such-lib.sh" gate_clamp 6)"
  has "$out" "MAX=6" "lib NOT loaded + agent.toml MISSING -> GATE_MAX_REVIEWERS stays 6 (never invents a cap, does not abort under set -e)"; has "$out" "UNREADABLE" "and says so"
  mv "$C/agents/gate-reviewer/agent.toml.off" "$C/agents/gate-reviewer/agent.toml"
  out="$(PATH="$SEDFAIL:$PATH" POOL_CEILING_LIB="$TMPROOT/no-such-lib.sh" gate_clamp 6)"
  has "$out" "MAX=6" "lib NOT loaded + sed FAILS on a readable agent.toml -> GATE_MAX_REVIEWERS stays 6 (survives set -euo pipefail)"; has "$out" "UNREADABLE" "and says so"
  out="$(PATH="$SEDFAIL:$PATH" gate_clamp 6)"
  has "$out" "MAX=2" "lib loaded + sed FAILS + fragment 2 -> the fragment's 2 (the lower bound it could read)"
  # order: the clamp runs AFTER the loader, or it would always take the fallback
  l_end=$(grep -n 'SELFTEST-EXTRACT pool-ceiling-loader: END' "$GATE" | head -1 | cut -d: -f1)
  l_call=$(grep -n '^_gate_clamp_to_engine_cap$' "$GATE" | head -1 | cut -d: -f1)
  if [ -n "$l_end" ] && [ -n "$l_call" ] && [ "$l_call" -gt "$l_end" ]; then ok "the gate calls _gate_clamp_to_engine_cap AFTER the lib loader (line $l_call > $l_end)"; else bad "the gate must call _gate_clamp_to_engine_cap after the lib loader (loader END $l_end, call $l_call)"; fi
  l_log=$(grep -n 'GATE_ENGINE_CAP_NOTE:-}" \] && log' "$GATE" | head -1 | cut -d: -f1)
  if [ -n "$l_log" ] && [ -n "$l_call" ] && [ "$l_log" -gt "$l_call" ]; then ok "and the note is logged after it is set"; else bad "the GATE_ENGINE_CAP_NOTE log line must come after the clamp (log $l_log, call $l_call)"; fi
  unset GC_CITY POOL_CEILING_LIB
fi

# ── 4. the Pilot ──────────────────────────────────────────────────────────────
section "4. pilot-dispatcher.sh: the REAL clamp block (static / shadow path), bash 3.2-safe"
PCLAMP_X="$(sed -n '/SELFTEST-EXTRACT pilot-clamp-engine-cap: BEGIN/,/SELFTEST-EXTRACT pilot-clamp-engine-cap: END/p' "$PILOT" 2>/dev/null)"
if [ -z "$PCLAMP_X" ]; then
  bad "RED on the pre-fix tree: no SELFTEST-EXTRACT pilot-clamp-engine-cap block in $PILOT (nothing ties PILOT_WA_WORKER_MAX / PILOT_PS_WORKER_MAX to the engine's cap)"
else
  pilot_clamp() { # <WA> <PS> [lib-ok 1|0] — env from the caller (GC_CITY). Prints LOG/WARN lines then "WA=<n> PS=<n>"
    bash -c '
      set -uo pipefail
      . "$1"
      _POOL_CEILING_OK="$5"
      log() { echo "LOG:$*"; }
      warn() { echo "WARN:$*"; }
      eval "$2"
      PILOT_WA_WORKER_MAX="$3"; PILOT_PS_WORKER_MAX="$4"
      _pilot_clamp_to_engine_cap
      echo "WA=$PILOT_WA_WORKER_MAX PS=$PILOT_PS_WORKER_MAX"
    ' _ "$LIB" "$PCLAMP_X" "$1" "$2" "${3:-1}" 2>&1
  }
  mk_city p1; export GC_CITY="$C"
  frag "wa-worker=2 ps-worker=1"
  out="$(pilot_clamp 4 2)"
  has "$out" "WA=2 PS=1" "RED on the pre-fix tree: fragment wa-worker=2 ps-worker=1 (agent.toml 4 / 2), Pilot caps 4 / 2 -> clamped to 2 / 1"
  has "$out" "PILOT_WA_WORKER_MAX 4 limitado ao teto do motor 2" "the sweep log says the wa-worker cap was limited, and to what"
  has "$out" "PILOT_PS_WORKER_MAX 2 limitado ao teto do motor 1" "and the ps-worker cap too"
  out="$(pilot_clamp 2 1)"; has "$out" "WA=2 PS=1" "caps already at the engine's: untouched"; lacks "$out" "limitado" "and nothing is logged"
  out="$(pilot_clamp 1 1)"; has "$out" "WA=1 PS=1" "a Pilot cap BELOW the engine's is never raised"
  out="$(pilot_clamp 0 0)"; has "$out" "WA=0 PS=0" "0 (the operator's pause) is untouched"
  out="$(pilot_clamp "" banana)"; has "$out" "WA= PS=banana" "empty / garbage is not ours to fix here: untouched"
  : > "$(FR)"
  out="$(pilot_clamp 4 2)"; has "$out" "WA=4 PS=2" "fragment EMPTY -> agent.toml's 4 / 2 stand (the clamp to agent.toml alone is a no-op here)"
  out="$(pilot_clamp 6 3)"; has "$out" "WA=4 PS=2" "static caps above agent.toml are brought down to it (the controller enforces agent.toml, ga-o3o09z)"
  rm -f "$(FR)"
  out="$(pilot_clamp 6 3)"; has "$out" "WA=4 PS=2" "fragment ABSENT -> agent.toml's caps"
  printf 'garbage\n' > "$(FR)"
  out="$(pilot_clamp 6 3)"; has "$out" "WA=4 PS=2" "fragment FOREIGN -> agent.toml's caps (no raise on a read failure)"
  out="$(pilot_clamp 4 2)"; has "$out" "ESTRANHO" "and a foreign fragment is said out loud even when nothing needed clamping"
  frag "wa-worker=2 ps-worker=1"; mv "$C/agents/wa-worker/agent.toml" "$C/agents/wa-worker/agent.toml.off"; rm -f "$C/agents/ps-worker/agent.toml"
  out="$(pilot_clamp 4 2)"; has "$out" "WA=2 PS=1" "agent.toml unreadable + fragment -> the fragment's levels"
  rm -f "$(FR)"
  out="$(pilot_clamp 4 2)"; has "$out" "WA=4 PS=2" "agent.toml unreadable + no fragment -> caps left as they are"; has "$out" "WARN:wa-worker: teto do motor ILEGIVEL" "with a warning, not silence"
  mv "$C/agents/wa-worker/agent.toml.off" "$C/agents/wa-worker/agent.toml"
  frag "wa-worker=2 ps-worker=1"
  out="$(pilot_clamp 4 2 0)"; has "$out" "WA=4 PS=2" "lib NOT loaded -> nothing changes (as before this bead)"
  # strict mode, as the dispatchers may run it
