  DYN_X="$(sed -n '/SELFTEST-EXTRACT pilot-apply-dynamic-pool-ceilings: BEGIN/,/SELFTEST-EXTRACT pilot-apply-dynamic-pool-ceilings: END/p' "$PILOT" 2>/dev/null)"
