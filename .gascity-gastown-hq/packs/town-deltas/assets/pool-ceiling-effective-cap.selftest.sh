  out="$(sweep clamp-first 2 "$(fresh)" POOL_CEILING_DYNAMIC=1 POOL_CEILING_SHADOW=1)"; has "$out" "WA=3" "dynamic in SHADOW (decides but does not apply) -> 3: the followed cap is what applies"
