#!/usr/bin/env bash
# pool-ceiling-effective-cap.selftest.sh (ga-m9x0lb.4, ga-m9x0lb.5)
#
# Proves that the dispatchers' view of "the cap the CONTROLLER will run" is the EFFECTIVE one, with ONE definition per pool: the engine's
# fragment entry (.gc/pool-ceiling-engine.toml, ga-m9x0lb) when it has one, else agents/<pool>/agent.toml — but never above the engine's own
# raise ceiling (wa-worker 3, every other pool its agent.toml) and, when the fragment cannot be read, the engine's FLOOR (never agent.toml).
# Measured 26/10 00:42: the engine had written gate-reviewer=2 (disk < 6 GB) and quality-gate-dispatcher.sh still logged "clamped to the
# engine cap 3" (.4); and the min(agent.toml, fragment) that fixed it pinned wa-worker at agent.toml's 2 while the engine raised it to 3 (.5).
#   1. pool_ceiling_engine_cap_resolve / pool_ceiling_engine_cap (pool-ceiling.sh): fragment 2 + agent.toml 3 -> 2; fragment absent / empty /
#      without an entry -> agent.toml; ps-worker / gate-reviewer ABOVE agent.toml -> agent.toml; wa-worker 3 over agent.toml 2 -> 3 (.5);
#      fragment foreign, unreadable, not a regular file or its reader missing -> the engine floor AND the doubt flagged and named (.5);
#      agent.toml unreadable -> the fragment's level. The lib's floor/ceiling table is checked against the engine's own functions.
#   2. pool_ceiling_step: the dynamic ceiling is bounded by the effective cap too (and can climb to the raised wa-worker level).
#   3. the gate's REAL clamp block, extracted from quality-gate-dispatcher.sh, run under `set -euo pipefail` (the gate's mode).
#   4. the Pilot's REAL clamp block, extracted from pilot-dispatcher.sh: down always, UP only for a pool the engine raised (.5), run BEFORE
#      the dynamic step, which is run here in the file's own order.
# Hermetic: every scenario runs against a throwaway city under a temp dir; nothing under the real city is read or written.
# Run against the pre-patch tree to confirm RED. Override: POOL_CEILING_LIB / PILOT_DISPATCHER_PATH / GATE_DISPATCHER_PATH.

set -uo pipefail

SELF_DIR="$(cd "$(dirname "${BASH_SOURCE[0]}")" && pwd)"
LIB="${POOL_CEILING_LIB:-$SELF_DIR/pool-ceiling.sh}"
PILOT="${PILOT_DISPATCHER_PATH:-$SELF_DIR/pilot-dispatcher.sh}"
GATE="${GATE_DISPATCHER_PATH:-$SELF_DIR/quality-gate-dispatcher.sh}"

PASS=0; FAIL=0
ok()  { echo "  ✓ $*"; PASS=$((PASS+1)); }
bad() { echo "  ✗ $*"; FAIL=$((FAIL+1)); }
eq()  { if [ "$1" = "$2" ]; then ok "$3 (got: $1)"; else bad "$3 (expected: $2, got: $1)"; fi; }
has() { case "$1" in *"$2"*) ok "$3" ;; *) bad "$3 (missing '$2' in: $1)" ;; esac; }
lacks() { case "$1" in *"$2"*) bad "$3 (found '$2' in: $1)" ;; *) ok "$3" ;; esac; }
section() { echo; echo "── $* ──"; }

TMPROOT="$(mktemp -d)"
trap 'chmod -R u+rw "$TMPROOT" 2>/dev/null; rm -rf "$TMPROOT"' EXIT
# Never let a LIVE switch / fragment of the real city leak into this hermetic test.
export POOL_CEILING_ON_FILE="$TMPROOT/on.flag" POOL_CEILING_KILL_FILE="$TMPROOT/kill.off" POOL_CEILING_SHADOW_FILE="$TMPROOT/shadow.flag"
unset POOL_CEILING_ENGINE_FRAGMENT POOL_CEILING_ENGINE_SH POOL_CEILING_AGENTS_DIR POOL_CEILING_DYNAMIC GC_CITY

C=""
mk_city() { # <name> — wa-worker 4, ps-worker 2, gate-reviewer 3 in agent.toml; NO fragment yet
  C="$TMPROOT/$1"; mkdir -p "$C/.gc" "$C/agents/wa-worker" "$C/agents/ps-worker" "$C/agents/gate-reviewer"
  printf 'min_active_sessions = 0\nmax_active_sessions = 4\n' > "$C/agents/wa-worker/agent.toml"
  printf 'min_active_sessions = 0\nmax_active_sessions = 2\n' > "$C/agents/ps-worker/agent.toml"
  printf 'max_active_sessions = 3 # gate\nmin_active_sessions = 0\n' > "$C/agents/gate-reviewer/agent.toml"
}
mk_real() { # <name> — the PRODUCTION shape (26/10): wa-worker 2, ps-worker 1, gate-reviewer 3 in agent.toml; NO fragment yet
  mk_city "$1"
  printf 'min_active_sessions = 0\nmax_active_sessions = 2\n' > "$C/agents/wa-worker/agent.toml"
  printf 'min_active_sessions = 0\nmax_active_sessions = 1\n' > "$C/agents/ps-worker/agent.toml"
}
frag() { # <"pool=level ..."> — a fragment in the shape the engine renders (header comments + [[patches.agent]] blocks)
  local e; { printf '# GENERATED by pool-ceiling-engine.sh\n# Empty or comment-only = no override.\n'; for e in $1; do printf '\n[[patches.agent]]\ndir = ""\nname = "%s"\nmax_active_sessions = %s\n' "${e%%=*}" "${e#*=}"; done; } > "$C/.gc/pool-ceiling-engine.toml"
}
FR() { echo "$C/.gc/pool-ceiling-engine.toml"; }

# resolve <pool> — runs the resolver in a fresh bash under the dispatchers' strict mode and prints "cap=<n> base=<n> doubt=<x>|<src>".
resolve() {
  bash -c 'set -euo pipefail; . "$1"; pool_ceiling_engine_cap_resolve "$2"; printf "cap=%s base=%s doubt=%s|%s" "$POOL_CEILING_ENGINE_CAP" "$POOL_CEILING_ENGINE_CAP_BASE" "$POOL_CEILING_ENGINE_CAP_DOUBT" "$POOL_CEILING_ENGINE_CAP_SRC"' _ "$LIB" "$1" 2>&1
}
cap_of() { printf '%s' "${1%%|*}" ; }

# ── 1. the resolver ───────────────────────────────────────────────────────────
section "1. pool_ceiling_engine_cap_resolve: the EFFECTIVE cap = the smaller of agent.toml and the fragment's entry"
export POOL_CEILING_AGENTS_DIR=""
mk_city c1; export POOL_CEILING_AGENTS_DIR="$C/agents"

# The case the bead is about. On the pre-fix tree pool_ceiling_engine_cap reads agent.toml alone and answers 3.
frag "gate-reviewer=2"
eq "$(bash -c 'set -euo pipefail; . "$1"; pool_ceiling_engine_cap gate-reviewer' _ "$LIB" 2>&1)" "2" "RED on the pre-fix tree: fragment gate-reviewer=2 + agent.toml 3 -> pool_ceiling_engine_cap says 2"
out="$(resolve gate-reviewer)"
eq "$(cap_of "$out")" "cap=2 base=3 doubt=" "resolve: cap 2, agent.toml alone is 3, no doubt"
has "$out" "fragmento pool-ceiling-engine.toml 2 (< agents/gate-reviewer/agent.toml 3)" "and the note says the number came from the fragment, and that it is below agent.toml"

frag "wa-worker=2 ps-worker=1 gate-reviewer=2"
eq "$(cap_of "$(resolve wa-worker)")" "cap=2 base=4 doubt=" "three entries: wa-worker is read from ITS entry (4 -> 2)"
eq "$(cap_of "$(resolve ps-worker)")" "cap=1 base=2 doubt=" "three entries: ps-worker is read from ITS entry (2 -> 1)"

# found / not-found: nothing overrides -> agent.toml stands, and the note says why
: > "$(FR)"
out="$(resolve gate-reviewer)"; eq "$(cap_of "$out")" "cap=3 base=3 doubt=" "fragment EMPTY (the kill switch's state) -> agent.toml 3, no doubt"; has "$out" "vazio" "the note says the fragment is empty"
printf '# only comments\n\n' > "$(FR)"
out="$(resolve gate-reviewer)"; eq "$(cap_of "$out")" "cap=3 base=3 doubt=" "fragment comment-only -> agent.toml 3"
rm -f "$(FR)"
out="$(resolve gate-reviewer)"; eq "$(cap_of "$out")" "cap=3 base=3 doubt=" "fragment ABSENT -> agent.toml 3, no doubt (no engine installed = nothing overrides)"; has "$out" "ausente" "the note says the fragment is absent"
frag "wa-worker=1"
out="$(resolve gate-reviewer)"; eq "$(cap_of "$out")" "cap=3 base=3 doubt=" "fragment with an entry for ANOTHER pool only -> agent.toml 3"; has "$out" "sem entrada para gate-reviewer" "the note says there is no entry for the pool"

# never a raise: a fragment ABOVE agent.toml (wa-worker, Athos rule) is not followed upward by a brake
frag "gate-reviewer=5"
out="$(resolve gate-reviewer)"; eq "$(cap_of "$out")" "cap=3 base=3 doubt=" "fragment 5 > agent.toml 3 -> 3 (a brake never raises)"; has "$out" "nao e menor" "the note says the fragment is not lower"

# could-not-find-out (ga-m9x0lb.5): the fragment EXISTS but cannot be consulted -> the engine's FLOOR (2 for the gate: what the engine itself restarts a
# pool from when it cannot read the levels), never agent.toml's 3 — a read failure must not raise the admitted count — and the doubt is flagged + named
printf 'garbage\n' > "$(FR)"
out="$(resolve gate-reviewer)"; eq "$(cap_of "$out")" "cap=2 base=3 doubt=1" "fragment FOREIGN -> the engine floor 2 (not agent.toml 3) AND doubt=1"; has "$out" "ESTRANHO" "the note says the fragment is foreign"; has "$out" "NAO consultado" "and that it was NOT consulted"; has "$out" "piso do motor 2" "and that the number is the engine's floor"
printf '[[patches.agent]]\ndir = ""\nname = "gate-reviewer"\nmax_active_sessions = 2\nmax_active_sessions = 1\n' > "$(FR)"
out="$(resolve gate-reviewer)"; eq "$(cap_of "$out")" "cap=2 base=3 doubt=1" "fragment with a DUPLICATED key (not what the engine writes) -> foreign -> the floor 2, doubt=1"
printf '[[patches.agent]]\ndir = ""\nname = "gate-reviewer"\nmax_active_sessions = 1 # hand\n' > "$(FR)"
out="$(resolve gate-reviewer)"; eq "$(cap_of "$out")" "cap=2 base=3 doubt=1" "valid TOML with a trailing '# hand' (the engine's strict parser calls it foreign) -> the floor 2, doubt=1, not agent.toml's 3"
frag "gate-reviewer=2"
if [ "$(id -u)" = "0" ]; then echo "  - SKIPPED: unreadable-fragment case (running as root, chmod 000 does not stop a read)"
else
  chmod 000 "$(FR)"
  if [ -r "$(FR)" ]; then echo "  - SKIPPED: unreadable-fragment case (chmod 000 did not make the file unreadable here)"
  else
    out="$(resolve gate-reviewer)"; eq "$(cap_of "$out")" "cap=2 base=3 doubt=1" "fragment UNREADABLE -> the floor 2 AND doubt=1 (never read as 'no override' silently)"; has "$out" "ilegivel" "the note says it is unreadable"
  fi
  chmod 644 "$(FR)"
fi
out="$(POOL_CEILING_ENGINE_SH="$TMPROOT/does-not-exist.sh" resolve gate-reviewer)"
eq "$(cap_of "$out")" "cap=2 base=3 doubt=1" "the engine's reader MISSING while a fragment exists -> the floor 2 (the lib's own table), doubt=1"; has "$out" "indisponivel" "the note says the reader is unavailable"
out="$(POOL_CEILING_ENGINE_SH="$SELF_DIR/pool-ceiling.sh" resolve gate-reviewer)"
eq "$(cap_of "$out")" "cap=2 base=3 doubt=1" "a reader that does not define pce_fragment_parse -> the floor 2, doubt=1 (a broken reader is not 'no entry')"

# agent.toml unreadable
frag "gate-reviewer=2"; mv "$C/agents/gate-reviewer/agent.toml" "$C/agents/gate-reviewer/agent.toml.off"
out="$(resolve gate-reviewer)"; eq "$(cap_of "$out")" "cap=2 base= doubt=" "agent.toml MISSING + fragment 2 -> the fragment's 2 (a known lower bound beats a guess)"
rm -f "$(FR)"
out="$(resolve gate-reviewer)"; eq "$(cap_of "$out")" "cap= base= doubt=" "agent.toml MISSING + no fragment -> EMPTY (could not find out), never a number"; has "$out" "ILEGIVEL" "the note says the cap is unreadable"
eq "$(bash -c 'set -euo pipefail; . "$1"; pool_ceiling_engine_cap gate-reviewer; echo END' _ "$LIB" 2>&1)" "END" "pool_ceiling_engine_cap prints NOTHING when unreadable, and survives set -euo pipefail"
mv "$C/agents/gate-reviewer/agent.toml.off" "$C/agents/gate-reviewer/agent.toml"

# the READ itself fails: agent.toml is there and readable but `sed` exits non-zero (a stub that fails — the [ -r ] guard above is not what is under test)
SEDFAIL="$TMPROOT/sed-fails"; mkdir -p "$SEDFAIL"; printf '#!/bin/sh\nexit 2\n' > "$SEDFAIL/sed"; chmod +x "$SEDFAIL/sed"
frag "gate-reviewer=2"
out="$(PATH="$SEDFAIL:$PATH" resolve gate-reviewer)"; eq "$(cap_of "$out")" "cap=2 base= doubt=" "sed FAILS on a readable agent.toml + fragment 2 -> the fragment's 2, agent.toml read as unknown (survives set -euo pipefail)"
rm -f "$(FR)"
out="$(PATH="$SEDFAIL:$PATH" resolve gate-reviewer)"; eq "$(cap_of "$out")" "cap= base= doubt=" "sed FAILS + no fragment -> EMPTY, never a number"; has "$out" "ILEGIVEL" "and the note says the cap is unreadable"
eq "$(PATH="$SEDFAIL:$PATH" bash -c 'set -euo pipefail; . "$1"; pool_ceiling_engine_cap gate-reviewer; echo END' _ "$LIB" 2>&1)" "END" "pool_ceiling_engine_cap with a failing sed prints NOTHING and survives set -euo pipefail"

# the seams
mk_city c1b; export POOL_CEILING_AGENTS_DIR="$C/agents"
LIVELIKE="$TMPROOT/livelike"; mkdir -p "$LIVELIKE/.gc"; printf '[[patches.agent]]\ndir = ""\nname = "gate-reviewer"\nmax_active_sessions = 1\n' > "$LIVELIKE/.gc/pool-ceiling-engine.toml"
out="$(GC_CITY="$LIVELIKE" resolve gate-reviewer)"
eq "$(cap_of "$out")" "cap=3 base=3 doubt=" "hermetic: with POOL_CEILING_AGENTS_DIR set, a fragment under GC_CITY (the live one) is NOT read"
frag "gate-reviewer=2"
out="$(POOL_CEILING_ENGINE_FRAGMENT="$LIVELIKE/.gc/pool-ceiling-engine.toml" resolve gate-reviewer)"
eq "$(cap_of "$out")" "cap=1 base=3 doubt=" "POOL_CEILING_ENGINE_FRAGMENT wins over the path derived from the agents dir"
unset POOL_CEILING_AGENTS_DIR
out="$(GC_CITY="$C" resolve gate-reviewer)"
eq "$(cap_of "$out")" "cap=2 base=3 doubt=" "production shape (no seams, GC_CITY set): agents/ and .gc/ both come from GC_CITY"
out="$(resolve gate-reviewer)"
eq "$(cap_of "$out")" "cap= base= doubt=" "no GC_CITY and no seam -> unknown (empty), never a guess"

# ── 1b. ga-m9x0lb.5: ONE definition per pool ──────────────────────────────────
section "1b. production shape (wa-worker 2, ps-worker 1, gate-reviewer 3): the fragment commands wa-worker both ways, up to the engine's 3"
mk_real r1; export POOL_CEILING_AGENTS_DIR="$C/agents"
frag "wa-worker=3"
out="$(resolve wa-worker)"; eq "$(cap_of "$out")" "cap=3 base=2 doubt=" "RED on the .4 tree: fragment wa-worker=3 over agent.toml 2 -> 3 (the engine's raise is followed; min() pinned it at 2)"; has "$out" "pool-ceiling-engine.toml 3 (> agents/wa-worker/agent.toml 2" "and the note says the fragment RAISED it above agent.toml"
eq "$(bash -c 'set -euo pipefail; . "$1"; pool_ceiling_engine_cap wa-worker' _ "$LIB" 2>&1)" "3" "pool_ceiling_engine_cap (value only) says 3 as well"
frag "wa-worker=2"; eq "$(cap_of "$(resolve wa-worker)")" "cap=2 base=2 doubt=" "fragment wa-worker=2 (the engine back at the committed value) -> 2"
frag "wa-worker=5"; eq "$(cap_of "$(resolve wa-worker)")" "cap=3 base=2 doubt=" "fragment wa-worker=5 is ABOVE the engine's raise ceiling 3 -> 3 (never followed past what the engine writes)"
frag "gate-reviewer=2"; eq "$(cap_of "$(resolve wa-worker)")" "cap=2 base=2 doubt=" "fragment without a wa-worker entry -> agent.toml 2"
: > "$(FR)"; eq "$(cap_of "$(resolve wa-worker)")" "cap=2 base=2 doubt=" "fragment EMPTY -> agent.toml 2"
rm -f "$(FR)"; eq "$(cap_of "$(resolve wa-worker)")" "cap=2 base=2 doubt=" "fragment ABSENT -> agent.toml 2"
frag "ps-worker=2 gate-reviewer=5"
eq "$(cap_of "$(resolve ps-worker)")" "cap=1 base=1 doubt=" "ps-worker is never raised (fragment 2 over agent.toml 1 -> 1)"
eq "$(cap_of "$(resolve gate-reviewer)")" "cap=3 base=3 doubt=" "gate-reviewer is never raised (fragment 5 over agent.toml 3 -> 3: still min(agent.toml, fragment))"
frag "wa-worker=3"; mv "$C/agents/wa-worker/agent.toml" "$C/agents/wa-worker/agent.toml.off"
eq "$(cap_of "$(resolve wa-worker)")" "cap=3 base= doubt=" "agent.toml unreadable + fragment 3 -> the fragment's 3 (a level it could read)"
frag "wa-worker=7"; eq "$(cap_of "$(resolve wa-worker)")" "cap=3 base= doubt=" "agent.toml unreadable + fragment 7 -> still capped at the raise ceiling 3"
mv "$C/agents/wa-worker/agent.toml.off" "$C/agents/wa-worker/agent.toml"
mk_city r1b; export POOL_CEILING_AGENTS_DIR="$C/agents"   # agent.toml wa-worker 4: the raise ceiling is max(3, agent.toml), never below the committed value
frag "wa-worker=3"; eq "$(cap_of "$(resolve wa-worker)")" "cap=3 base=4 doubt=" "agent.toml 4 + fragment 3 -> 3 (a lowering is followed, as before)"
: > "$(FR)"; eq "$(cap_of "$(resolve wa-worker)")" "cap=4 base=4 doubt=" "agent.toml 4 + no entry -> 4"

section "1c. could not read the fragment -> the engine FLOOR per pool (what the engine restarts a pool from), never above agent.toml"
mk_real r2; export POOL_CEILING_AGENTS_DIR="$C/agents"
printf 'garbage\n' > "$(FR)"
eq "$(cap_of "$(resolve wa-worker)")" "cap=2 base=2 doubt=1" "foreign fragment: wa-worker -> its floor 2"
eq "$(cap_of "$(resolve ps-worker)")" "cap=1 base=1 doubt=1" "foreign fragment: ps-worker -> its floor 1"
eq "$(cap_of "$(resolve gate-reviewer)")" "cap=2 base=3 doubt=1" "foreign fragment: gate-reviewer -> its floor 2 (one gate run needs 2 reviewers)"
printf 'min_active_sessions = 0\nmax_active_sessions = 1\n' > "$C/agents/gate-reviewer/agent.toml"
eq "$(cap_of "$(resolve gate-reviewer)")" "cap=1 base=1 doubt=1" "the floor is never ABOVE agent.toml (agent.toml 1 < floor 2 -> 1)"
mv "$C/agents/gate-reviewer/agent.toml" "$C/agents/gate-reviewer/agent.toml.off"
out="$(resolve gate-reviewer)"; eq "$(cap_of "$out")" "cap= base= doubt=1" "foreign fragment AND agent.toml unreadable -> EMPTY (could not find out), never a guessed number"; has "$out" "ILEGIVEL" "and the note says the cap is unreadable"

# (b) a fragment path that is not a regular file: a DIRECTORY read as an empty fragment ('vazio', 3) and a dangling symlink as 'ausente' (3)
mk_real r3; export POOL_CEILING_AGENTS_DIR="$C/agents"
mkdir "$(FR)"
out="$(resolve gate-reviewer)"; eq "$(cap_of "$out")" "cap=2 base=3 doubt=1" "a DIRECTORY at the fragment path -> the floor 2, doubt=1 (it read as 'vazio' and 3)"; has "$out" "NAO e um arquivo comum" "and the note says it is not a regular file"
rmdir "$(FR)"; ln -s "$C/.gc/no-such-target.toml" "$(FR)"
out="$(resolve gate-reviewer)"; eq "$(cap_of "$out")" "cap=2 base=3 doubt=1" "a DANGLING symlink at the fragment path -> the floor 2, doubt=1 (it read as 'ausente' and 3)"
rm -f "$(FR)"; frag "gate-reviewer=2"; mv "$(FR)" "$C/.gc/real-fragment.toml"; ln -s "$C/.gc/real-fragment.toml" "$(FR)"
out="$(resolve gate-reviewer)"; eq "$(cap_of "$out")" "cap=2 base=3 doubt=" "a symlink to a regular fragment is read through (not an error)"
rm -f "$(FR)" "$C/.gc/real-fragment.toml"
if [ "$(id -u)" = "0" ]; then echo "  - SKIPPED: unsearchable-.gc case (running as root, chmod 000 does not stop a stat)"
else
  frag "gate-reviewer=2"; chmod 000 "$C/.gc"
  if [ -x "$C/.gc" ]; then echo "  - SKIPPED: unsearchable-.gc case (chmod 000 did not make the directory unsearchable here)"
  else out="$(resolve gate-reviewer)"; eq "$(cap_of "$out")" "cap=2 base=3 doubt=1" "the fragment's directory is NOT searchable (stat fails: cannot tell absent from present) -> the floor 2, doubt=1, not 'ausente'"; fi
  chmod 755 "$C/.gc"
fi

# (d) sed | head -1 under pipefail: with a long agent.toml sed takes SIGPIPE and `|| v=""` threw the valid first line away
mk_real r4; export POOL_CEILING_AGENTS_DIR="$C/agents"
awk 'BEGIN { for (i = 0; i < 40000; i++) print "max_active_sessions = 3" }' > "$C/agents/gate-reviewer/agent.toml"; : > "$(FR)"
out="$(resolve gate-reviewer)"; eq "$(cap_of "$out")" "cap=3 base=3 doubt=" "a 40000-line agent.toml: the first line still counts (it read as unreadable under pipefail)"

# the lib's floor/ceiling table MIRRORS the engine's pce_floor / pce_ceil (default knobs). The engine file is the one that can be missing, so the lib
# cannot source it for these two numbers; this is what keeps the two from drifting apart unnoticed.
ENG="$SELF_DIR/pool-ceiling-engine.sh"; drift=""
for p in wa-worker ps-worker gate-reviewer mila-wa; do for cv in 1 2 3 4 5 9; do
  want="$(env -i PATH="$PATH" HOME="${HOME:-/}" bash -c '. "$1" >/dev/null 2>&1; pce_init; echo "$(pce_floor "$2" "$3") $(pce_ceil "$2" "$3")"' _ "$ENG" "$p" "$cv" 2>&1)"
  got="$(bash -c '. "$1"; echo "$(_pc_engine_floor "$2" "$3") $(_pc_engine_ceil "$2" "$3")"' _ "$LIB" "$p" "$cv" 2>&1)"
  [ "$want" = "$got" ] || drift="$drift [$p C=$cv engine='$want' lib='$got']"
done; done
eq "$drift" "" "the lib's floor/ceiling table agrees with pool-ceiling-engine.sh (pce_floor, pce_ceil) for 4 pools x 6 committed values"

# ── 2. the step ───────────────────────────────────────────────────────────────
section "2. pool_ceiling_step: the dynamic ceiling never goes above the effective cap either"
mk_city c2; export POOL_CEILING_AGENTS_DIR="$C/agents"
step() { # <fixed> <min> <max> — prints RESULT; calm machine, queue 5, 3 live, dynamic ON
  bash -c '
    set -euo pipefail
    . "$1"
    export POOL_CEILING_DYNAMIC=1 POOL_CEILING_STATE_DIR="$2" POOL_CEILING_NOW=5000 POOL_CEILING_DRY=1
    export POOL_CEILING_T_LOAD5=31 POOL_CEILING_T_NCPU=10 POOL_CEILING_T_MEM=1 POOL_CEILING_T_SWAP_FREE_MB=5700 POOL_CEILING_T_SWAP_USED_MB=412 POOL_CEILING_T_DISK_FREE_MB=14336
    pool_ceiling_step gate-reviewer "$3" "$4" "$5" 3 5 ok ok
    printf "%s" "$POOL_CEILING_RESULT"
  ' _ "$LIB" "$TMPROOT/st.$RANDOM" "$1" "$2" "$3" 2>&1
}
frag "gate-reviewer=2"
eq "$(step 3 2 6)" "2" "RED on the pre-fix tree: fixed 3, bounds 2..6, fragment gate-reviewer=2 -> the ceiling is 2"
: > "$(FR)"
eq "$(step 3 2 6)" "3" "control: fragment empty -> 3 (agent.toml's cap), the step still works as before"
frag "gate-reviewer=2"; mv "$C/agents/gate-reviewer/agent.toml" "$C/agents/gate-reviewer/agent.toml.off"
eq "$(step 3 2 6)" "2" "agent.toml unreadable + fragment 2 -> 2 (and never above the fixed 3 on that doubt)"
mv "$C/agents/gate-reviewer/agent.toml.off" "$C/agents/gate-reviewer/agent.toml"
step_wa() { # <fixed> — wa-worker, bounds 1..4, 2 live (saturated at 2), queue 5, calm machine, dynamic ON; prints RESULT
  bash -c '
    set -euo pipefail
    . "$1"
    export POOL_CEILING_DYNAMIC=1 POOL_CEILING_STATE_DIR="$2" POOL_CEILING_NOW=5000 POOL_CEILING_DRY=1
    export POOL_CEILING_T_LOAD5=31 POOL_CEILING_T_NCPU=10 POOL_CEILING_T_MEM=1 POOL_CEILING_T_SWAP_FREE_MB=5700 POOL_CEILING_T_SWAP_USED_MB=412 POOL_CEILING_T_DISK_FREE_MB=14336
    pool_ceiling_step wa-worker "$3" 1 4 2 5 ok ok
    printf "%s" "$POOL_CEILING_RESULT"
  ' _ "$LIB" "$TMPROOT/st.$RANDOM" "$1" 2>&1
}
mk_real c2b; export POOL_CEILING_AGENTS_DIR="$C/agents"
frag "wa-worker=3"; eq "$(step_wa 2)" "3" "RED on the .4 tree: wa-worker fixed 2, queue 5, 2 live, calm machine, fragment wa-worker=3 over agent.toml 2 -> the ramp climbs to 3"
frag "wa-worker=2"; eq "$(step_wa 2)" "2" "control: fragment at 2 -> the ramp stays at 2 (its ceiling is the engine's)"
: > "$(FR)"; eq "$(step_wa 2)" "2" "control: fragment empty -> 2 (agent.toml)"
printf 'garbage\n' > "$(FR)"; eq "$(step_wa 3)" "2" "foreign fragment + fixed 3 -> the engine floor 2 bounds the ramp"

# ── 3. the gate ───────────────────────────────────────────────────────────────
section "3. quality-gate-dispatcher.sh: the REAL clamp block, run under set -euo pipefail"
unset POOL_CEILING_AGENTS_DIR
LOADER_X="$(sed -n '/SELFTEST-EXTRACT pool-ceiling-loader: BEGIN/,/SELFTEST-EXTRACT pool-ceiling-loader: END/p' "$GATE" 2>/dev/null)"
