  sweep() { # <clamp-first|clamp-last> <plist WA> [VAR=value ...] — the REAL blocks in the given order, calm machine, queue 3, 2 live; prints LOG/WARN lines then "WA=<n>"
    local order="$1" plist="$2"; shift 2
